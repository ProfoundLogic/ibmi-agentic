#!/bin/bash
# Load the PRFDEMOLIB sample data into a library built by codermake, and
# create the runtime support objects codermake has no recipe for.
#
#   prfdemolib/tools/load-prfdemo-data.sh [--no-seed] <TARGETLIB> [SOURCELIB]
#
# TARGETLIB  library the prfdemolib targets were built into
#            (normally $IBMI_BUILD_LIBRARY)
# SOURCELIB  library holding the shipped sample data (default PRFDEMOLIB).
#            Only read, never written.
#
# What it does, all inside TARGETLIB:
#   1. CPYF every non-empty physical file from SOURCELIB (MBROPT(*REPLACE)).
#      The reconstructed DDS has the same format level identifiers as the
#      shipped files, so FMTOPT(*NONE) is used and a mismatch fails loudly.
#      ORDERBK: the rows live in member OB01; they are copied into the single
#      member codermake creates (the shipped ORDERBK member holds the same
#      three rows), which is what INV502 reads through ORDERBK1.
#   2. CHGPF STR001WK MAXMBRS(*NOMAX)  - TS0110 F10 adds one member per run.
#   3. CRTDTAARA MBRSEQNO *DEC(7 0) VALUE(9000000) if missing - NXTSEQ.
#   4. Seed extra demo data (skip with --no-seed): 24 SKUs in dept 86
#      SEASONAL CANDY and dept 59 BEDDING, 5 vendors, pack-and-hold rows and
#      4 inventory groups. SQL is generated by tools/gen-seed-data.py (see its
#      header) and run with QSH db2; it deletes what it adds first.
#
# Not created: JOBD IMSJOB1. The shipped TS0110 submitted CLTS0111 with it;
# the demo profile has no authority to CRTJOBD/CRTDUPOBJ a job description, so
# TS0110 was changed (PRF1) to submit with CURLIB(<library TS0110 runs from>).
#
# Re-runnable: data is replaced, MBRSEQNO is kept if it already exists.
set -euo pipefail

SEED=1
if [ "${1:-}" = "--no-seed" ]; then SEED=0; shift; fi
TGT=${1:?usage: $0 [--no-seed] TARGETLIB [SOURCELIB]}
SRC=${2:-PRFDEMOLIB}
TGT=$(echo "$TGT" | tr a-z A-Z); SRC=$(echo "$SRC" | tr a-z A-Z)
SSH_HOST=${PRFDEMO_SSH_HOST:-dev}

case "$TGT" in
  PRFDEMOLIB|AIDEMOBASE|QSYS|QGPL) echo "Refusing to load into $TGT" >&2; exit 1;;
esac
[ "$TGT" = "$SRC" ] && { echo "TARGETLIB and SOURCELIB must differ" >&2; exit 1; }

# Physical files that carry sample rows in PRFDEMOLIB, with their member.
FILES="APSUPP INVADI INVBAL INVBAL1 INVCBL INVDPT INVFSD INVMST INVVEN ITMRTL
OPTIONS OPTSTR ORDERBK:OB01 PHPF PHPFW2 RPLPRF SKVAUX TBLADI TBLBYR TBLDST
TBLFLD TBLREG TBLSEA TBLSTR TBL800 TRFDTL"

rc=0
ssh "$SSH_HOST" "TGT=$TGT SRC=$SRC FILES='$FILES' /QOpenSys/usr/bin/sh -s" <<'REMOTE' || rc=$?
set -u
rc=0
run() {   # run a CL command, print it and its messages, remember failures
  out=$(system -kpieb "$1" 2>&1); r=$?
  printf '%s\n' "> $1"
  [ -n "$out" ] && printf '%s\n' "$out" | grep -E '^(CP|MCH|SQL)[A-Z0-9]{4}' | sed 's/^/    /'
  return $r
}
[ -d /qsys.lib/$TGT.lib ] || { echo "Library $TGT not found"; exit 1; }
for f in $FILES; do
  file=${f%%:*}; mbr=${f#*:}; [ "$mbr" = "$f" ] && mbr='*FIRST'
  if [ ! -e /qsys.lib/$TGT.lib/$file.file ]; then
    echo "!! $TGT/$file missing - build prfdemolib with codermake first"; rc=1; continue
  fi
  run "CPYF FROMFILE($SRC/$file) TOFILE($TGT/$file) FROMMBR($mbr) TOMBR(*FIRST) MBROPT(*REPLACE) FMTOPT(*NONE)" || rc=1
done

run "CHGPF FILE($TGT/STR001WK) MAXMBRS(*NOMAX)" || rc=1

if [ ! -e /qsys.lib/$TGT.lib/MBRSEQNO.DTAARA ]; then
  run "CRTDTAARA DTAARA($TGT/MBRSEQNO) TYPE(*DEC) LEN(7 0) VALUE(9000000) TEXT('DEMO - TS0110 work member sequence')" || rc=1
else
  echo "= $TGT/MBRSEQNO exists, kept"
fi


exit $rc
REMOTE

if [ $SEED -eq 1 ]; then
  echo "> Seeding extra demo items into $TGT (tools/gen-seed-data.py)"
  HERE=$(cd "$(dirname "$0")" && pwd)
  python3 "$HERE/gen-seed-data.py" | sed "s/{LIB}/$TGT/g" |
    ssh "$SSH_HOST" "cat > /tmp/prfseed_$TGT.sql &&
      /QOpenSys/usr/bin/qsh -c 'db2 -t -f /tmp/prfseed_$TGT.sql' > /tmp/prfseed_$TGT.out 2>&1;
      ok=\$(grep -c 'COMPLETED SUCCESSFULLY' /tmp/prfseed_$TGT.out);
      bad=\$(grep 'SQLSTATE' /tmp/prfseed_$TGT.out | grep -vc 'SQLSTATE: 02000');
      echo \"    \$ok statements OK, \$bad failed (details: /tmp/prfseed_$TGT.out on the IBM i)\";
      rm -f /tmp/prfseed_$TGT.sql; [ \$bad -eq 0 ]" || rc=1
fi

echo
[ $rc -eq 0 ] && echo "Load into $TGT complete." || echo "Load into $TGT finished WITH ERRORS (see above)."
exit $rc
