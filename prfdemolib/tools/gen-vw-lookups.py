#!/usr/bin/env python3
"""Write prfdemolib/web/src/lookups.js - the client-side catalogue behind the
type-ahead pickers on the web screens (options 10-12).

The green screens' F4/F3 prompt programs (TBL048, TBL049, TBL009, TBL018,
TBL064, INV002) are not part of the PRFDEMOLIB restore. The web versions
replace them with browser-side pickers fed by this catalogue, generated from
the same tables the RPG reads, so a suggestion is always a value the program
will accept.

    python3 prfdemolib/tools/gen-vw-lookups.py <LIBRARY> > prfdemolib/web/src/lookups.js
    python3 prfdemolib/web/build.py

Re-run after reloading or reseeding data.
"""
import json
import os
import subprocess
import sys

LIB = sys.argv[1].upper() if len(sys.argv) > 1 else sys.exit(__doc__)
HOST = os.environ.get('PRFDEMO_SSH_HOST', 'dev')


def q(sql):
    sql = sql.replace('{L}', LIB)
    out = subprocess.run(['ssh', HOST, '/QOpenSys/pkgs/bin/db2util -o json "%s"' % sql],
                         capture_output=True, text=True, check=True).stdout
    rows = json.loads(out)['records']
    return [{k: (v.strip() if isinstance(v, str) else v) for k, v in r.items()} for r in rows]


def i(v):
    return int(float(v))


stores = q("select STRNUM, STSHRT, STCITY, STPVST, STRHDO, STRWHS, REGNUM, STRDST, STRNAM, ZONNUM "
           "from {L}.TBLSTR order by STRNUM")
regions = q("select r.REGNUM, r.REGNAM, (select count(*) from {L}.TBLSTR s where s.REGNUM = r.REGNUM "
            "and s.STRHDO = 'S') N from {L}.TBLREG r order by 1")
districts = q("select STRDST, DSTNAM, REGNUM from {L}.TBLDST order by 1")
groups = q("select h.ADINUM, h.ADINAM, (select count(*) from {L}.INVADI d where d.ADINUM = h.ADINUM) N "
           "from {L}.TBLADI h order by 1")
invgroups = q("select h.INGNUM, h.INGNAM, (select count(*) from {L}.TBLIGD d where d.INGNUM = h.INGNUM) N "
              "from {L}.TBLIGH h order by 1")
depts = q("select d.IDEPT, d.DPTNAM, (select count(*) from {L}.INVMST m where m.IDEPT = d.IDEPT) N "
          "from {L}.INVDPT d where d.ISDEPT = 0 and d.ICLAS = 0 and d.ISCLAS = 0 order by 1")
seasons = q("select SEANUM, SEADSC from {L}.TBLSEA order by 1")
skus = q("select INUMBR, IDESCR, IDEPT from {L}.INVMST order by 1")

cat = {
    'generated': 'from library %s by prfdemolib/tools/gen-vw-lookups.py' % LIB,
    'stores': [{'n': i(s['STRNUM']), 'short': s['STSHRT'], 'city': ('%s, %s' % (s['STCITY'].title(), s['STPVST'])).strip(', '),
                'type': s['STRHDO'], 'wh': i(s['STRWHS']), 'reg': i(s['REGNUM']), 'dst': i(s['STRDST']),
                'name': ' '.join(s['STRNAM'].title().split()), 'zone': i(s['ZONNUM'])} for s in stores],
    'regions': [{'n': i(r['REGNUM']), 'name': r['REGNAM'].title(), 'stores': i(r['N'])} for r in regions],
    'districts': [{'n': i(d['STRDST']), 'name': 'District %s - %s' % (i(d['STRDST']), d['DSTNAM'].title()), 'reg': i(d['REGNUM'])} for d in districts],
    'groups': [{'n': i(g['ADINUM']), 'name': g['ADINAM'].title(), 'stores': i(g['N'])} for g in groups],
    'invgroups': [{'n': i(g['INGNUM']), 'name': g['INGNAM'].title(), 'stores': i(g['N'])} for g in invgroups],
    'depts': [{'n': i(d['IDEPT']), 'name': d['DPTNAM'].title(), 'skus': i(d['N'])} for d in depts if i(d['N'])],
    'seasons': [{'c': s['SEANUM'], 'd': s['SEADSC'].title()} for s in seasons],
    'skus': [{'n': i(s['INUMBR']), 'd': s['IDESCR'], 'dept': i(s['IDEPT'])} for s in skus],
}
sys.stdout.write('/* GENERATED by prfdemolib/tools/gen-vw-lookups.py - do not edit by hand.\n'
                 ' * Client-side catalogue for the type-ahead pickers that replace the F4\n'
                 ' * prompt programs missing from the demo restore. */\n'
                 'window.VW_LOOKUPS = ' + json.dumps(cat, separators=(',', ':')) + ';\n')
