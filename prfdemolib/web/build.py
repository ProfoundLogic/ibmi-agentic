#!/usr/bin/env python3
"""Assemble the PRFDEMOLIB web screens into the Profound UI asset tree:
the plain web versions of the green screens (menu options 7-9, vp* apps,
vpshared/plain.css) and the Variety Wholesalers demo screens (options 10-12,
vw* apps, vwshared/).

    python3 prfdemolib/web/build.py            # build
    python3 prfdemolib/web/build.py --check    # fail if htdocs is out of date

Sources (edit these):   prfdemolib/web/src/
    app.css, app.js, lookups.js     -> htdocs/.../vwshared/
    plain.css                       -> htdocs/.../vpshared/
    vw_logo.png                     -> inlined into vwshared/theme.css
    partials/*.ejs                  -> spliced into templates at <%# include:name %>
    <app>/<format>.ejs|.css|.js     -> htdocs/.../<app>/
Output (do not edit):   htdocs/profoundui/userdata/ui/vwshared|vwinv046|vwinv502|vwts0110/
                        htdocs/profoundui/userdata/ui/vpshared|vpinv046|vpinv502|vpts0110/

Every template is compiled with the real ejs library as a syntax check.
"""
import base64
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src')
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(REPO, 'htdocs', 'profoundui', 'userdata', 'ui')
APPS = ['vwinv046', 'vwinv502', 'vwts0110', 'vpinv046', 'vpinv502', 'vpts0110']
CHECK = '--check' in sys.argv

outputs = {}


def emit(rel, data):
    outputs[rel] = data if isinstance(data, bytes) else data.encode('utf-8')


def read(p, mode='r'):
    with open(p, mode) as fh:
        return fh.read()


partials = {os.path.splitext(f)[0]: read(os.path.join(SRC, 'partials', f))
            for f in os.listdir(os.path.join(SRC, 'partials')) if f.endswith('.ejs')}

# location names for the templates' first paint (screen JS - and so the full
# catalogue - may not have loaded yet when the template renders)
import json as _json
_lk = read(os.path.join(SRC, 'lookups.js'))
_lk = _json.loads(_lk[_lk.index('=') + 1:_lk.rindex(';')])
def _dc(name):
    name = re.sub(r'\s*\([^)]*\)', '', name)
    name = re.sub(r'\bDist Ctr\b', 'DC', name)
    name = re.sub(r'\bDc\b', 'DC', name)
    return re.sub(r'\bGa\b', 'GA', name).strip()
_loc = {str(s['n']): [_dc(s['name']) if s['type'] == 'W' else s['short'], s['city'], s['type'], s['wh']] for s in _lk['stores']}
partials['helpers'] = partials['helpers'].replace('/*VWLOC*/{}', _json.dumps(_loc, separators=(',', ':')))
partials['helpers'] = partials['helpers'].replace('/*VWSEA*/[]', _json.dumps([[x['c'], x['d']] for x in _lk['seasons']], separators=(',', ':')))
partials['skumap'] = '<' + '% var VWSKU = ' + _json.dumps({str(x['n']): x['d'] for x in _lk['skus']}, separators=(',', ':')) + '; %' + '>'


def expand(text, name):
    def sub(m):
        key = m.group(1)
        if key not in partials:
            sys.exit('%s: unknown partial %s' % (name, key))
        return partials[key].rstrip('\n')
    return re.sub(r'<%#\s*include:([a-z0-9_-]+)\s*%>', sub, text)


logo = base64.b64encode(read(os.path.join(SRC, 'vw_logo.png'), 'rb')).decode('ascii')
emit('vwshared/theme.css',
     '/* GENERATED by prfdemolib/web/build.py - Variety Wholesalers logo (vwstores.com\n'
     ' * VW_logo.png) inlined so the brand mark never needs a second fetch. */\n'
     '.vw-app { --vw-logo: url("data:image/png;base64,%s"); }\n' % logo)
for f in ('app.css', 'app.js', 'lookups.js'):
    emit('vwshared/' + f, read(os.path.join(SRC, f)))
emit('vpshared/plain.css', read(os.path.join(SRC, 'plain.css')))

# Formats that can share a response with a later, active subfile-control
# format. Profound UI renders EVERY format of the layer into ONE container,
# each one as soon as its template arrives over XHR - so the last template to
# arrive wins, not the active format. TS0110 writes WAITWIN before the SKU list
# and leaves DISTWIN/NONEWIN on the layer under it; INV502 leaves SCREEN1 under
# SCREEN2C. A guarded format therefore renders the list/detail screen itself
# whenever that screen's subfile is in the data (Profound UI merges the data of
# every format in the layer), so either arrival order shows the right screen.
#   (app, format) -> (format to render instead, subfile that proves it is there)
GUARDS = {}
for _tier in ('vw', 'vp'):
    for _f in ('waitwin', 'distwin', 'nonewin'):
        GUARDS[(_tier + 'ts0110', _f)] = ('skuctl', 'skusfl')
    GUARDS[(_tier + 'inv502', 'screen1')] = ('screen2c', 'screen2s')


def guarded(app, fmt, own):
    other, sfl = GUARDS[(app, fmt)]
    body = expand(read(os.path.join(SRC, app, other + '.ejs')), other + '.ejs')
    return ('<% if (typeof ' + sfl + ' !== \'undefined\' && ' + sfl + ') { %>\n' + body.rstrip('\n') +
            '\n<% } else { %>\n' + own.rstrip('\n') + '\n<% } %>\n')


templates = []
for app in APPS:
    d = os.path.join(SRC, app)
    if not os.path.isdir(d):
        continue
    for f in sorted(os.listdir(d)):
        p = os.path.join(d, f)
        if f.endswith('.ejs'):
            text = expand(read(p), f)
            fmt = f[:-4]
            if (app, fmt) in GUARDS:
                text = guarded(app, fmt, text)
            emit(app + '/' + f, text)
            templates.append(app + '/' + f)
        elif f.endswith(('.css', '.js')):
            emit(app + '/' + f, read(p))

# syntax-check every template with the real ejs compiler
node_check = r'''
const ejs = require(process.argv[1]); const fs = require('fs');
let bad = 0;
for (const f of process.argv.slice(2)) {
  try { ejs.compile(fs.readFileSync(f, 'utf8'), { client: true }); }
  catch (e) { bad++; console.error('EJS syntax error in ' + f + ': ' + e.message); }
}
process.exit(bad ? 1 : 0);
'''
ejs_mod = os.path.expanduser('~/.claude/skills/dspf-to-ejs/node_modules/ejs')
tmp = os.path.join('/tmp', 'vwbuild')
if os.path.isdir(tmp):
    shutil.rmtree(tmp)
os.makedirs(tmp)
paths = []
for t in templates:
    p = os.path.join(tmp, t.replace('/', '__'))
    with open(p, 'wb') as fh:
        fh.write(outputs[t])
    paths.append(p)
if os.path.isdir(ejs_mod):
    r = subprocess.run(['node', '-e', node_check, ejs_mod] + paths)
    if r.returncode:
        sys.exit('template syntax check failed')
for rel, data in outputs.items():
    if rel.endswith('.js'):
        p = os.path.join(tmp, rel.replace('/', '__'))
        with open(p, 'wb') as fh:
            fh.write(data)
        if subprocess.run(['node', '--check', p]).returncode:
            sys.exit('JS syntax error in ' + rel)

stale = []
for rel, data in sorted(outputs.items()):
    dest = os.path.join(OUT, rel)
    cur = read(dest, 'rb') if os.path.exists(dest) else None
    if cur != data:
        stale.append(rel)
        if not CHECK:
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, 'wb') as fh:
                fh.write(data)
if CHECK and stale:
    sys.exit('out of date: ' + ', '.join(stale))
print('%d files, %d %s' % (len(outputs), len(stale), 'stale' if CHECK else 'written'))
