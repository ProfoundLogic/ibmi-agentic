    changed = workday(min(TODAY, created + dt.timedelta(days=random.randint(0, 12))))
    oh_rows.append((oh_yy, oh_n, pp, dc, stat, code, meth, vend, frt, buyer,
                    created.isoformat(), buyer, changed.isoformat(),
                    '%02d.%02d.%02d' % (random.randint(7, 17), random.randint(0, 59), random.randint(0, 59)),
                    nn, cid, loc, ship[0], 'RECEIVING DEPT', ship[1], ship[2], ship[3], ship[4], ship[5],
                    'USA', '', ordid, 0, '', '', '', 'X'))

    total = 0.0
    for ln, part in enumerate(picked, start=1):
        (p, pv, maj, mino, sku, desc, desc2, uom, lead, per, cost, pct) = PARTBY[part]
        qty = pick_qty(part, random)
        unit = round(cost * random.uniform(0.97, 1.04), 5)
        due = workday(created + dt.timedelta(days=lead))
        if stat == 'C':
            lstat, rq = 'C', qty
        elif stat == 'X':
            lstat, rq = 'X', 0
        elif age > 50 and stat == ' ':
            lstat, rq = ' ', 0                     # overdue, nothing received
        else:
            lstat = ' '
