# Material group -> requisition type code, so OMCODE always matches the part.
# Target line value by material group, so a PO looks like something a buyer
# would really raise: you do not order ten press felts, and you do not raise a
# purchase order for three square inches of printing plate.
VALUE_BAND = {
    '110': (6000, 40000),   # starch
    '120': (4000, 30000),   # wet end chemicals
    '130': (19000, 45000),  # paper machine clothing
    '140': (18000, 60000),  # corrugator rolls and belts
    '150': (1500, 18000),   # flexo print consumables
    '160': (2000, 25000),   # recycling / baling
    '170': (1500, 14000),   # shipping supplies
    '180': (2000, 20000),   # retail display
    '190': (400, 7000),     # plant MRO and PPE
    '900': (150, 1500),     # freight and services
}

def pick_qty(part, rnd):
    (p, pv, maj, mino, sku, desc, desc2, uom, lead, per, cost, pct) = PARTBY[part]
    lo, hi = VALUE_BAND.get(maj, (1000, 10000))
    target = rnd.uniform(lo, hi)
    if cost <= 0:
        return 1
    qty = target / float(cost)
    if per > 1:                       # order in whole packs
        packs = max(1, int(round(qty / per)))
        qty = packs * per
    else:
        qty = max(1, int(round(qty)))
        for step in (1000, 500, 100, 50, 25, 10, 5):
            if qty >= step * 2:
                qty = int(round(qty / step)) * step
                break
    return qty


