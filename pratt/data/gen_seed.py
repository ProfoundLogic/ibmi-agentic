def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def emit(sql):
    OUT.append(sql if sql.lstrip().startswith('--') else sql + ';')


def ins(table, cols, rows):
    if not rows:
        return
    emit('DELETE FROM %s' % table)
    for r in rows:
        vals = ', '.join(q(v) if isinstance(v, str) else str(v) for v in r)
        emit('INSERT INTO %s (%s) VALUES (%s)' % (table, ', '.join(cols), vals))


def workday(d):
    while d.weekday() >= 5:
        d -= dt.timedelta(days=1)
    return d


def biz(days_ago):
    return workday(TODAY - dt.timedelta(days=days_ago))


def cymd(d):
    return int(d.strftime('%Y%m%d')) - 19000000 if d.year >= 1900 else 0


