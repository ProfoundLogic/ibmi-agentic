#!/usr/bin/env node
/*
 * GT Warehouse Mobile -- the cache-stamp lint.
 *
 *   node gtwms/tools/lint-cache-stamps.js
 *
 * TWO RULES:
 *   1. every asset URL in every display-file JSON carries a ?v= stamp;
 *   2. all of them carry the SAME stamp;
 *   3. the JS files that guard their own re-entry declare that same stamp as
 *      their VERSION.
 *
 * WHY. Screen assets reach the browser by TWO routes at once: the display file
 * lists them in "css"/"js", so the browser loads a `<script src=...?v=stamp>`
 * tag; and the Genie shim injects a base64 snapshot, which is always fresh.
 * `gt-scan.js` guards its own re-entry, so WHICHEVER RUNS FIRST WINS -- and a
 * `<script src>` with a stale stamp is served from cache.
 *
 * That is how three consecutive camera fixes were deployed, verified in the
 * snapshot, and still not running on the device: `gtitmd.json` and two others
 * had **no ?v= stamp at all**, so their copy of gt-scan.js could never be
 * evicted, and the months-old file installed itself before the fresh snapshot
 * could. The operator reported the same error three times while every check
 * passed.
 *
 * The guards now compare versions so newer wins regardless of order -- but that
 * only works if the stamp is actually bumped, which is what this checks.
 *
 * After changing any css/js: bump the stamp in EVERY display file, rebuild the
 * display files and their programs, deploy, and re-shim.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const DDS = path.resolve(__dirname, '../qddssrc');
const UI = path.resolve(__dirname, '../../htdocs/profoundui/userdata/ui');

/* Files that install a singleton on window and therefore need a version. */
const GUARDED = ['gtcommon/gt-scan.js', 'gtcommon/gt-photo.js'];

let pass = 0, fail = 0;
const ok = (m, d) => { pass++; console.log('  PASS  ' + m + (d ? '  -- ' + d : '')); };
const bad = (m, d) => { fail++; console.log('  FAIL  ' + m + (d ? '  -- ' + d : '')); };

const ASSET = /"(\/profoundui\/userdata\/ui\/[^"]+)"/g;

const stamps = new Map();      /* stamp -> [where] */
const missing = [];

for (const f of fs.readdirSync(DDS).filter((x) => x.endsWith('.json'))) {
  const text = fs.readFileSync(path.join(DDS, f), 'utf8');
  let m;
  ASSET.lastIndex = 0;
  while ((m = ASSET.exec(text)) !== null) {
    const url = m[1];
    const q = url.indexOf('?v=');
    if (q < 0) {
      missing.push(f + '  ' + url);
      continue;
    }
    const stamp = url.slice(q + 3);
    if (!stamps.has(stamp)) stamps.set(stamp, []);
    stamps.get(stamp).push(f);
  }
}

console.log('=== cache stamps in the display files ===\n');

if (missing.length) {
  missing.slice(0, 8).forEach((x) => bad('asset URL with NO ?v= stamp', x));
  console.log('\n  An unstamped URL is cached forever. This is exactly how a');
  console.log('  months-old gt-scan.js kept beating the fresh shim snapshot.');
} else {
  ok('every asset URL carries a ?v= stamp',
     [...stamps.values()].reduce((n, v) => n + v.length, 0) + ' URLs');
}

if (stamps.size > 1) {
  const list = [...stamps.entries()]
    .map(([s, files]) => s + ' (' + [...new Set(files)].length + ' files)')
    .join(', ');
  bad('the stamps disagree', list);
  console.log('\n  One stamp for the whole application: a per-file stamp means');
  console.log('  remembering which screens changed, which is how some got left behind.');
} else if (stamps.size === 1) {
  ok('one stamp across every display file', [...stamps.keys()][0]);
}

/* The guarded singletons must declare the same version, or "newer wins" has
 * nothing to compare. */
const stamp = stamps.size === 1 ? [...stamps.keys()][0] : null;
if (stamp) {
  for (const rel of GUARDED) {
    const p = path.join(UI, rel);
    if (!fs.existsSync(p)) { bad(rel + ' is missing'); continue; }
    const src = fs.readFileSync(p, 'utf8');
    const m = src.match(/var\s+VERSION\s*=\s*'([^']+)'/);
    if (!m) {
      bad(rel + ' declares no VERSION',
          'without it a stale copy cannot be told apart from a fresh one');
    } else if (m[1] !== stamp) {
      bad(rel + ' VERSION is ' + m[1], 'display files say ' + stamp);
    } else {
      ok(rel + ' VERSION matches the stamp', stamp);
    }
  }
}

console.log('\n' + (fail ? 'FAILED' : 'Clean') + ': ' + pass + ' passed, ' + fail + ' failed');
/* gt-version.js is how a stale page discovers it is stale, so a stamp that
   disagrees with the display files would either never trigger an upgrade or
   trigger one for ever. It is generated by deploy-assets.sh; this catches the case
   where somebody bumped the stamp and has not deployed yet. */
if (stamp) {
  const vf = path.join(UI, 'gtcommon', 'gt-version.js');
  if (!fs.existsSync(vf)) {
    bad('gtcommon/gt-version.js is missing', 'generated by deploy-assets.sh -- a stale page cannot self-upgrade without it');
  } else {
    const m = fs.readFileSync(vf, 'utf8').match(/__gtStamp\s*=\s*'([0-9a-z]+)'/);
    if (m && m[1] === stamp) ok('gt-version.js advertises the current stamp', stamp);
    else bad('gt-version.js advertises the wrong stamp', 'says ' + (m ? m[1] : '?') + ', display files say ' + stamp);
  }
}

process.exit(fail ? 1 : 0);
